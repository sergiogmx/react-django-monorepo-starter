// Turns tokens.json (W3C Design Tokens format) into theme.css, a Tailwind v4
// `@theme` block. tokens.json is the single source; never edit theme.css by hand.
// Run with `make tokens`. CI fails if theme.css is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('./tokens.json', import.meta.url)));

// Tailwind reads a single `--spacing` base unit instead of a named scale.
const RENAMES = { 'spacing-base': 'spacing' };

function formatValue(value) {
  if (Array.isArray(value)) {
    return value.map((font) => (/\s/.test(font) ? `"${font}"` : font)).join(', ');
  }
  if (typeof value === 'object' && value !== null && 'unit' in value) {
    return `${value.value}${value.unit}`;
  }
  return String(value);
}

function collect(node, path, out) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const childPath = [...path, key];
    if (child && typeof child === 'object' && '$value' in child) {
      const name = childPath.join('-');
      out.push([RENAMES[name] ?? name, formatValue(child.$value)]);
    } else if (child && typeof child === 'object') {
      collect(child, childPath, out);
    }
  }
  return out;
}

const lines = collect(tokens, [], []).map(([name, value]) => `  --${name}: ${value};`);

const css = `/* Generated by packages/tokens/build.mjs from tokens.json. Do not edit by hand. */
@theme {
${lines.join('\n')}
}
`;

writeFileSync(new URL('./theme.css', import.meta.url), css);
console.log(`theme.css written with ${lines.length} tokens`);
